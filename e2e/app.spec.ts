test('the app floats above other windows and comes back as it was', async ({ page, context }) => {
  const errors = await start(page)
  test.skip(!(await page.evaluate(() => 'documentPictureInPicture' in window)), 'No Document Picture-in-Picture in this browser')
  await page.getByRole('tab', { name: 'Kort' }).click()
  await page.getByRole('button', { name: 'Flere valg' }).click()
  const opened = context.waitForEvent('page')
  await page.getByRole('button', { name: 'Vis over andre vinduer' }).click()
  const pip = await opened
  await expect(pip.getByRole('button', { name: 'Flere valg' })).toBeFocused()
  await pip.evaluate(() => document.addEventListener('securitypolicyviolation', e => console.error(`CSP: ${e.violatedDirective}`)))
  pip.on('console', m => m.type() === 'error' && errors.push(m.text()))
  await expect(page.getByText('Trix vises i et eget vindu over de andre')).toBeVisible()
  // Styles, theme and the app's state came along.
  await expect(pip.getByRole('tab', { name: 'Kort' })).toHaveAttribute('aria-selected', 'true')
  const background = (p: Page) => p.evaluate(() => getComputedStyle(document.body).backgroundColor)
  expect(await background(pip)).not.toBe('rgba(0, 0, 0, 0)')
  // Light unless the user chooses dark, also in the floating window on a dark device.
  await page.emulateMedia({ colorScheme: 'dark' })
  await pip.emulateMedia({ colorScheme: 'dark' })
  expect(await background(pip)).toBe('rgb(248, 250, 252)')
  // The folder picker needs the main window: no dot here.
  await expect(pip.locator('.badge')).toHaveCount(0)
  expect(await pip.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--size'))).not.toBe('')
  // Clicks, keys and links work in the floating window.
  await pip.getByRole('tab', { name: 'Oppslag' }).click()
  const mac = await page.evaluate(() => /mac/i.test(navigator.userAgent))
  await pip.keyboard.press(mac ? 'Meta+KeyF' : 'Control+KeyF')
  await expect(pip.getByRole('searchbox')).toBeFocused()
  await pip.keyboard.type('første')
  await pip.getByRole('button', { name: /Første oppslag/ }).click()
  await pip.keyboard.press('Escape')
  await expect(pip.getByRole('searchbox')).toHaveValue('første')
  // Backup and restore from the floating window; the question opens there, not behind it.
  await pip.getByRole('button', { name: 'Flere valg' }).click()
  const saved = pip.waitForEvent('download')
  await pip.locator('#menu summary').click()
  await pip.getByRole('button', { name: 'Lag sikkerhetskopi' }).click()
  const zip = await (await saved).path()
  await pip.getByRole('button', { name: 'Flere valg' }).click()
  const chooser = pip.waitForEvent('filechooser')
  pip.once('dialog', dialog => dialog.accept())
  await pip.locator('#menu summary').click()
  await pip.getByRole('button', { name: 'Hent sikkerhetskopi' }).click()
  await (await chooser).setFiles(zip)
  await expect(pip.getByText(/Hentet \d+ filer fra sikkerhetskopien/)).toBeVisible()
  await pip.getByRole('button', { name: 'Flere valg' }).click()
  await expect(pip.getByRole('button', { name: 'Vis over andre vinduer' })).toHaveCount(0)
  await page.keyboard.press(mac ? 'Meta+Digit3' : 'Control+Digit3')
  await expect(pip.getByRole('tab', { name: 'Oppslag' })).toHaveAttribute('aria-selected', 'true')
  await pip.getByRole('button', { name: 'Tilbake til hovedvinduet' }).click()
  await expect(page.getByRole('button', { name: 'Flere valg' })).toBeFocused()
  await expect(page.getByRole('tab', { name: 'Oppslag' })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('searchbox')).toHaveValue('første')
  await expect(page.getByText('Trix vises i et eget vindu over de andre')).toHaveCount(0)
  // Once more, and back with the button in the main window.
  await page.getByRole('button', { name: 'Flere valg' }).click()
  const again = context.waitForEvent('page')
  await page.getByRole('button', { name: 'Vis over andre vinduer' }).click()
  const { AxeBuilder } = await import('@axe-core/playwright')
  const { violations } = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa']).analyze()
  expect(violations.map(v => v.id)).toEqual([])
  const pip2 = await again
  await pip2.getByRole('button', { name: 'Flere valg' }).click()
  await pip2.getByRole('button', { name: 'Tilpass appen' }).click()
  await pip2.getByRole('button', { name: 'Legg til fane' }).click()
  await page.getByRole('button', { name: 'Vis Trix her' }).click()
  await expect(page.locator('dialog[open], :popover-open')).toHaveCount(0)
  await page.getByRole('button', { name: 'Avbryt' }).click()
  await page.keyboard.press(mac ? 'Meta+KeyF' : 'Control+KeyF')
  await expect(page.getByRole('searchbox')).toBeFocused()
  await expect(page.getByRole('tab', { name: 'Oppslag' })).toBeVisible()
  expect(errors).toEqual([])
})

